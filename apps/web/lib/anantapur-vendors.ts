import { KADAPA_VENDORS } from './kadapa-vendors';

export { KADAPA_VENDORS };

export const ALL_LOCAL_VENDORS: VendorItem[] = [...ANANTAPUR_VENDORS, ...KADAPA_VENDORS];

export function isCitySupported(city: string = ''): boolean {
  const norm = city.trim().toLowerCase();
  return norm === 'anantapur' || norm === 'kadapa';
}

export function getVendorsByCity(city: string = 'Anantapur'): VendorItem[] {
  const norm = city.trim().toLowerCase();
  if (norm === 'kadapa') {
    return KADAPA_VENDORS;
  }
  if (norm === 'anantapur') {
    return ANANTAPUR_VENDORS;
  }
  return [];
}

export function mapCategoryToSlug(categoryName: string): string {
  const c = (categoryName || '').toLowerCase();
  if (c.includes('venue') || c.includes('hall')) return 'venues';
  if (c.includes('cater') || c.includes('meal') || c.includes('food')) return 'caterers';
  if (c.includes('decor') || c.includes('mandap')) return 'decorators';
  if (c.includes('photo') || c.includes('video')) return 'photographers';
  if (c.includes('makeup') || c.includes('bridal')) return 'makeup-artists';
  if (c.includes('invite') || c.includes('card')) return 'invitation-designers';
  if (c.includes('dj') || c.includes('sound') || c.includes('music')) return 'djs';
  if (c.includes('mehendi') || c.includes('henna')) return 'mehendi-artists';
  if (c.includes('car') || c.includes('travel') || c.includes('transport') || c.includes('logistics')) return 'wedding-cars';
  if (c.includes('gift') || c.includes('return') || c.includes('cake')) return 'return-gifts';
  if (c.includes('plan') || c.includes('event')) return 'event-planners';
  return '';
}

export function getVendorsForCategory(categorySlugOrName: string, city: string = 'Anantapur'): VendorItem[] {
  const targetSlug = mapCategoryToSlug(categorySlugOrName) || categorySlugOrName.toLowerCase();
  if (!targetSlug) return [];

  const cityVendors = getVendorsByCity(city);
  return cityVendors.filter(
    (v) => v.categorySlug === targetSlug || v.categoryName.toLowerCase() === targetSlug
  );
}
